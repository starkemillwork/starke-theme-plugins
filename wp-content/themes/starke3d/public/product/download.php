// 1. Define your hidden CloudFront URL here (Server-side only)
define( 'STARKE_CATALOG_SECURE_URL', 'https://d260k5w9fy8qjz.cloudfront.net/wp-content/uploads/2026/01/01233758/Current-Edition-Catalog.pdf' );

// 2. Register the Shortcode [starke_catalog_button]
add_shortcode( 'starke_catalog_button', 'starke_render_secure_catalog_btn' );

function starke_render_secure_catalog_btn( $atts ) {
    // Generate a secure nonce (valid for 12-24 hours usually)
    $nonce = wp_create_nonce( 'starke_catalog_download' );
    
    // Create the obfuscated local link
    // It will look like: yoursite.com/?starke_action=download_catalog&_wpnonce=...
    $download_link = add_query_arg( array(
        'starke_action' => 'download_catalog',
        '_wpnonce'      => $nonce,
    ), home_url( '/' ) );

    // Output the button HTML using your "Gold" style
    // Note: We open in a new tab (_blank) to ensure the redirect works smoothly
    ob_start();
    ?>
    <a href="<?php echo esc_url( $download_link ); ?>" class="starke-3d-btn starke-catalog-btn" target="_blank">
        DOWNLOAD PDF CATALOG <i class="fa fa-download" style="margin-left: 10px;"></i>
    </a>
    <?php
    return ob_get_clean();
}

// 3. Listen for the Download Request
add_action( 'template_redirect', 'starke_handle_catalog_download' );

function starke_handle_catalog_download() {
    // Check if the specific query parameter is present
    if ( isset( $_GET['starke_action'] ) && $_GET['starke_action'] === 'download_catalog' ) {
        
        // A. Verify the Nonce (Security Check)
        // If the nonce is invalid or missing, this check fails and we stop.
        if ( ! isset( $_GET['_wpnonce'] ) || ! wp_verify_nonce( $_GET['_wpnonce'], 'starke_catalog_download' ) ) {
            wp_die( 'Security check failed. Please refresh the page and try again.', 'Secure Download Error', array( 'response' => 403 ) );
        }

        // B. If Valid, Redirect to the CloudFront URL
        // The user never sees the CloudFront URL in the HTML source code, only the final redirect.
        wp_redirect( STARKE_CATALOG_SECURE_URL );
        exit;
    }
}